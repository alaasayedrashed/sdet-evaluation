package com.sdet.evaluation.api.steps;

import static org.assertj.core.api.Assertions.assertThat;

import com.sdet.evaluation.api.client.UsersClient;
import com.sdet.evaluation.api.context.ScenarioContext;
import com.sdet.evaluation.api.models.CreateUserRequest;
import com.sdet.evaluation.api.models.CreateUserResponse;
import com.sdet.evaluation.api.models.User;
import com.sdet.evaluation.api.models.UserListResponse;
import io.cucumber.java.en.Given;
import io.cucumber.java.en.Then;
import io.cucumber.java.en.When;
import io.restassured.response.Response;

/**
 * Steps for the {@code /users} resource. Thin by design: HTTP details live in {@link UsersClient},
 * shared state lives in {@link ScenarioContext}.
 */
public class UsersSteps {

  private final UsersClient usersClient;
  private final ScenarioContext context;

  public UsersSteps(UsersClient usersClient, ScenarioContext context) {
    this.usersClient = usersClient;
    this.context = context;
  }

  @When("I request the users on page {int}")
  public void requestUsersOnPage(int page) {
    context.setLastResponse(usersClient.getUsers(page));
  }

  @Then("the users list should contain a user with id {int} and first name {string}")
  public void usersListShouldContainUser(int id, String expectedFirstName) {
    User user = findUserOnLastPage(id);

    assertThat(user.getFirstName()).as("first_name of user id %d", id).isEqualTo(expectedFirstName);
  }

  @Given("I have retrieved the user with id {int} from page {int}")
  public void retrieveUser(int id, int page) {
    Response response = usersClient.getUsers(page);
    context.setLastResponse(response);
    assertThat(response.statusCode())
        .as("GET /users?page=%d must succeed before its data can be reused", page)
        .isEqualTo(200);

    context.setSelectedUser(findUserOnLastPage(id));
  }

  @When("I create a new user from that user with job {string}")
  public void createUserFromSelectedUser(String job) {
    CreateUserRequest request = CreateUserRequest.fromUser(context.selectedUser(), job);
    context.setLastResponse(usersClient.createUser(request));
  }

  @Then("the created user should have a non-empty id")
  public void createdUserShouldHaveId() {
    assertThat(createdUser().getId())
        .as("'id' generated by the server for the new user")
        .isNotBlank();
  }

  private User findUserOnLastPage(int id) {
    UserListResponse page = context.lastResponse().as(UserListResponse.class);
    return page.findUserById(id)
        .orElseThrow(
            () ->
                new AssertionError(
                    "User with id %d not found on page %d; ids present: %s"
                        .formatted(
                            id,
                            page.getPage(),
                            page.getData().stream().map(User::getId).toList())));
  }

  private CreateUserResponse createdUser() {
    return context.lastResponse().as(CreateUserResponse.class);
  }
}
